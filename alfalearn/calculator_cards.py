"""Cards for the seven calculators of kurs.alfabank.ru.

Each card explains what the calculator does, the formulas and an example taken
from its page on the site, and links to the calculator itself. The bot does not
calculate anything here. Texts use Telegram HTML formatting.
"""

from dataclasses import dataclass

SITE = "https://kurs.alfabank.ru"


def calculator_url(slug: str) -> str:
    return f"{SITE}/calculators/{slug}/"


@dataclass(frozen=True, slots=True)
class CalculatorCard:
    command: str  # Telegram command without the slash: a-z, 0-9, _
    slug: str     # Calculator address on kurs.alfabank.ru
    title: str
    button: str   # Short name for menu buttons
    body: str

    @property
    def url(self) -> str:
        return calculator_url(self.slug)

    @property
    def text(self) -> str:
        return (
            f"🧮 <b>{self.title}</b>\n\n{self.body}\n\n"
            f'📎 Источник: <a href="{self.url}">«{self.title}», Альфа-Курс</a>'
        )


